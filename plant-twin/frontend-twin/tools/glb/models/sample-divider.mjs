/**
 * ПРИМЕР модели для проверки загрузки GLB: условный тестоделитель (не по фото, не конкретная марка).
 * Габариты ≈ 0,9 × 1,65 × 1,3 м. Шаблон для моделей по фотографиям: копируйте и меняйте размеры/детали.
 */
export const meta = { name: 'Тестоделитель (пример)', units: 'm', note: 'Условная модель для проверки загрузки' };

export function build({ mat, box, cyl, hopper, rodX, legs, group }) {
  const W = 0.8;
  const D = 0.9;
  return group(
    legs(W, D, 0.12, 0.03, mat.rubber, 0.08),
    box(W, 0.9, D, mat.brushed, 0, 0.12, 0, 'корпус'),
    box(W * 0.9, 0.02, 0.02, mat.steelDark, 0, 0.6, D / 2 + 0.01),
    box(0.24, 0.16, 0.03, mat.panel, W / 2 - 0.16, 0.82, D / 2 + 0.015, 'пульт'),
    box(0.12, 0.07, 0.01, mat.screen, W / 2 - 0.16, 0.86, D / 2 + 0.035),
    cyl(0.025, 0.03, mat.paintRed, W / 2 - 0.08, 0.86, D / 2 + 0.03, 16),
    box(W * 0.7, 0.25, D * 0.6, mat.steel, 0, 1.02, -0.05, 'головка'),
    hopper(0.7, 0.6, 0.32, 0.26, 0.38, mat.steel.clone(), 0, 1.27, -0.05),
    // отводящий транспортёр
    box(0.36, 0.05, 0.45, mat.black, 0, 0.66, D / 2 + 0.22, 'лента'),
    rodX(0.03, 0.38, mat.steelDark, 0, 0.66, D / 2 + 0.44),
    box(0.02, 0.1, 0.45, mat.steel, 0.19, 0.61, D / 2 + 0.22),
    box(0.02, 0.1, 0.45, mat.steel, -0.19, 0.61, D / 2 + 0.22),
  );
}
